// Baileys' crypto lives in whatsapp-rust-bridge, which compiles its WebAssembly from an
// inline base64 string at runtime. Cloudflare Workers don't allow that, so this script
// extracts the SIMD build to a .wasm file (imported as a module) and writes a patched
// copy of the JS next to it. Run again after upgrading baileys:  node scripts/build-wa-bridge.cjs
const fs = require('fs');
const path = require('path');
const src = fs.readFileSync(path.join(__dirname, '..', 'node_modules', 'whatsapp-rust-bridge', 'dist', 'index.js'), 'utf8');
const blobs = [...src.matchAll(/(tryInit|base64ToUint8Array)\("([A-Za-z0-9+/=]{1000,})"\)/g)];
if (blobs.length !== 2) throw new Error('unexpected bridge layout: ' + blobs.length + ' wasm blobs');
const out = path.join(__dirname, '..', 'src', 'wa');
fs.writeFileSync(path.join(out, 'bridge_simd.wasm'), Buffer.from(blobs[0][2], 'base64'));
const start = src.indexOf('var forceNoSimd');
const end = src.indexOf('export {', start);
if (start < 0 || end < 0) throw new Error('unexpected bridge layout (init block)');
const js = '// GENERATED by scripts/build-wa-bridge.cjs from whatsapp-rust-bridge. Do not edit.\n'
  + src.slice(0, start) + 'import __wasmMod from "./bridge_simd.wasm";\ninitSync({ module: __wasmMod });\nvar __wasmSimdActive = true;\n' + src.slice(end);
fs.writeFileSync(path.join(out, 'bridge.js'), js);
console.log('wrote src/wa/bridge.js and bridge_simd.wasm');
